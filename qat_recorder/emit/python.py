# -*- coding: utf-8 -*-
"""
Recording -> pytest module.

The generated file calls Qat's own API, so replay needs nothing from this project
at runtime. Two things are deliberate:

* **Fragile targets are flagged in the output.** A recording that depends on
  sibling ordering produces a script with a comment saying so, at the line that
  will break. Hiding it would make the script look more trustworthy than it is.
* **Secrets are never written.** A redacted value becomes a `secret()` lookup, so
  the file is safe to commit and fails loudly if the environment is not set up.
"""

from __future__ import annotations

import json
import keyword
import re
from typing import Any, Mapping

from qat_recorder.ir import ActionKind, Recording, Robustness, SECRET_KEY, is_secret

HEADER = '''"""
Generated by qat-recorder from a recorded session.

Regenerate rather than hand-edit: the recording in {source} is the source of
truth, and edits here are lost the next time it is re-emitted.
"""

import json
import os
import time

import pytest
import qat


def secret(name):
    """Look up a value that was deliberately not recorded.

    The recorder saw a field with a non-normal echoMode and refused to write its
    contents to disk. Supply it through the environment at replay time.
    """
    key = "QATREC_SECRET_" + name
    value = os.environ.get(key)
    if value is None:
        raise RuntimeError(
            "{{}} is not set; it holds a value the recorder redacted".format(key))
    return value
'''

#: Added only when the recording uses a menu. Qat finds a menu item through the
#: menu that contains it, so a menu that is not open fails as though the menu
#: itself had vanished -- "Unable to find object: {"objectName":"menuOptions"}"
#: -- which sends you looking for the wrong problem entirely.
#: Always added. An application that gives a control no objectName leaves only
#: its visible text to identify it, and visible text changes when the product is
#: translated or reworded. Nothing can invent an identity the application does
#: not have -- but everything can be pointed at a better one from a single
#: place, instead of editing every test that touches the control.
OVERRIDE_HELPER = '''

def _overrides():
    """Definitions supplied by hand, from objects.json beside this test.

    An object map. Where the recorder could only find a control by its visible
    text, put a better definition here -- an objectName someone added to the
    application, an accessibleName, anything stable -- and every test that uses
    that control picks it up. Nothing is overridden by default.
    """
    here = os.path.dirname(os.path.abspath(__file__))
    try:
        with open(os.path.join(here, "objects.json"), encoding="utf-8") as file:
            loaded = json.load(file)
    except (OSError, ValueError):
        return {}
    return {name: value for name, value in loaded.items()
            if not name.startswith("_") and isinstance(value, (dict, list))}


OVERRIDES = _overrides()


def find(candidates, timeout_ms=None):
    """The first of these definitions the application actually has, right now.

    Every step carries several ways to identify its object -- an objectName, the
    same plus a type, the text, each of those narrowed by a container -- and all
    of them were checked against the running application when the step was
    recorded. Trying them in order is what stops one renamed property from
    breaking a test that had three other ways to find the same button.

    It also waits. A control that is not there yet and a control that cannot be
    found are the same thing to a script, and the cure for both is to keep
    asking until the step's own timeout runs out. Waiting for it to be *usable*
    -- visible and enabled -- rather than merely present, because a dialog
    exists in the object tree before it has been drawn, and clicking into one
    that has not been drawn fails as "out-of-bounds".
    """
    if isinstance(candidates, dict):
        candidates = [candidates]
    # Bounded separately from the step timeout. That one is taken from the
    # longest pause in the session, which is right for "this application is
    # slow" and wrong for "this object is not coming": two minutes of waiting
    # tells you nothing that fifteen seconds did not.
    limit = (timeout_ms if timeout_ms is not None
             else min(TIMEOUT_MS, FIND_TIMEOUT_MS)) / 1000.0
    deadline = time.time() + limit

    while True:
        for definition in candidates:
            try:
                qat.wait_for_object(definition, timeout=250)
                return definition
            except (LookupError, RuntimeError):
                continue
        if time.time() >= deadline:
            break
        time.sleep(0.1)

    # Nothing matched. Say what was tried, in order, because the first one is
    # the one that used to work and the rest say how hard we looked.
    raise AssertionError(
        "none of these found a usable object after {:.0f}s:\\n  {}".format(
            limit, "\\n  ".join(repr(one) for one in candidates)))


def override(name, definition):
    return OVERRIDES.get(name, definition)
'''

#: Starting the application, which is not always the same thing as starting what
#: the recording was pointed at.
#:
#: A launch script sets up an environment, starts whatever daemons the product
#: needs and then runs the real binary as a CHILD. Qat waits for the process it
#: started to announce a port; the child announces it under its own pid, so a
#: test that registers the script directly gives up before its first step:
#:
#:     Abort: app terminated
#:
#: The recorder followed the application into that child while recording, and a
#: replay has to do the same or the test can never pass on the machine it was
#: recorded on. Where qat_recorder is not installed beside the test, a plain
#: launch is exactly right for a binary and is the only thing available anyway.
LAUNCH_HELPER = '''

def launch_application(name, path):
    """Start the application the way the recording started it."""
    try:
        from qat_recorder import launch
    except ImportError:
        if name not in qat.list_applications():
            qat.register_application(name, path)
        return qat.start_application(name)

    if path and launch.is_script(path):
        # Registered every time, not only when missing: a script has to be
        # launched through the recorder's wrapper, and a registration pointing
        # straight at it is the failure this function exists to prevent.
        launch.register_for_replay(qat, name, path)
    elif name not in qat.list_applications():
        launch.register_for_replay(qat, name, path)
    return launch.start(qat, name, app_path=path)


def close_application(context):
    """Close the application, and whatever started it."""
    try:
        from qat_recorder import launch
    except ImportError:
        qat.close_application(context)
        return
    launch.close(qat, context)

'''

#: Added only when the recording touches a row of a list, tree or table. Qat
#: addresses items by row number, which is wrong the moment a row is inserted
#: above the one that matters. The text is what the person recognised, so the
#: text is what this looks for -- and the recorded row is kept as a fallback for
#: views whose items have no text at all.
ITEM_HELPER = '''

def row(container, text, column=0, recorded=0, limit=500):
    """The row of `container` showing `text`, wherever it has moved to.

    Waits for the view itself to be on screen first. A dialog exists in the
    object tree the moment it is constructed, before it has been laid out, so a
    row inside it can be found and still have no rectangle to click -- which
    fails as "Item is not visible (out-of-bounds)", pointing at the row when the
    problem is that the dialog had not appeared yet.

    Falls back to the row that was recorded when nothing matches -- an item with
    no readable text, typically an icon or a checkbox column.
    """
    qat.wait_for_object(container)          # visible and enabled, not merely there

    if text:
        for index in range(limit):
            candidate = {"container": container, "row": index, "column": column}
            try:
                item = qat.wait_for_object_exists(candidate, timeout=200)
            except LookupError:
                break
            if str(getattr(item, "text", "")) == text:
                item.ScrollTo()
                return candidate
        raise AssertionError(
            "no row of {} says {!r}. It was row {} when this was recorded; the "
            "contents have changed.".format(container, text, recorded))

    candidate = {"container": container, "row": recorded, "column": column}
    qat.wait_for_object_exists(candidate).ScrollTo()
    return candidate


def click_row(container, text, column=0, recorded=0, select="", **kwargs):
    """Choose a row: by clicking it, or by telling the view to select it.

    Clicking is tried first, because it is what the person did and because on a
    tree it also expands. But Qat refuses to click an item whose rectangle lies
    outside its view -- "Item is not visible (out-of-bounds)" -- and there are
    views where that never stops being true: zero-height until a layout settles,
    a column drawn by a delegate, a row Qat can address but not place.

    Retrying that forever is what a script does when it has one way to do
    something. This has two. `select` names the property the view uses to say
    what is chosen (`currentRow` on a list, `currentIndex` on a tab widget) and
    setting it needs no geometry at all -- no scrolling, no visibility, no
    layout. It is not a click, so it is second, but it is the reason this step
    can succeed on a view that will never allow one.
    """
    view = find(container)
    candidate = row(view, text, column, recorded)
    deadline = time.time() + TIMEOUT_MS / 1000.0
    scrolled = False
    last = None

    while time.time() < deadline:
        try:
            qat.mouse_click(candidate, **kwargs)
            return candidate
        except RuntimeError as error:
            last = error
            if "not visible" not in str(error).lower():
                raise
            if not scrolled:
                scrolled = True
                try:
                    qat.wait_for_object_exists(candidate).ScrollTo()
                    continue
                except Exception:
                    pass
            break                      # scrolling did not help; stop hammering
        except LookupError as error:
            last = error
            time.sleep(0.2)

    if select:
        # Second way. Needs no geometry, so it works where clicking cannot.
        wanted = candidate.get("row", recorded)
        setattr(qat.wait_for_object(view), select, wanted)
        return candidate

    raise AssertionError(
        "could not choose row {} of {}: {}. The view gives no property to set "
        "the selection with either, so there is no second way to do it.".format(
            candidate.get("row", recorded), view, last))
'''

MENU_HELPER = '''

def menu_item(item):
    """Click a menu item, saying what actually went wrong if it is not there."""
    try:
        qat.mouse_click(item)
    except LookupError as error:
        raise AssertionError(
            "could not click the menu item {!r}: the menu holding it, {}, is "
            "not open. The step before this one should have opened it. If that "
            "step ran without complaint, something else had focus -- a dialog "
            "left open by an earlier step will do it.".format(
                item["text"], item["container"])) from error
'''


def is_item(definition: Any) -> bool:
    """Whether a definition addresses a row of a list, tree or table."""
    return isinstance(definition, Mapping) and "row" in definition \
        and "container" in definition


def is_menu_item(definition: Any) -> bool:
    """Whether a definition is Qat's form for a menu item.

    Recognised by shape rather than by the strategy that produced it, so a
    recording round-tripped through JSON is treated the same as a fresh one.
    """
    return (isinstance(definition, Mapping)
            and set(definition) == {"container", "text"})


def _identifier(text: str, fallback: str = "obj") -> str:
    cleaned = re.sub(r"[^0-9a-zA-Z_]+", "_", text or "").strip("_")
    if not cleaned:
        cleaned = fallback
    if cleaned[0].isdigit():
        cleaned = "_" + cleaned
    if keyword.iskeyword(cleaned):
        cleaned += "_"
    return cleaned


def _render(value: Any) -> str:
    """Render a value as a Python literal, with dict keys sorted for stability."""
    if is_secret(value):
        return f"secret({value[SECRET_KEY]!r})"
    if isinstance(value, Mapping):
        inner = ", ".join(f"{key!r}: {_render(value[key])}"
                          for key in sorted(value))
        return "{" + inner + "}"
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(_render(item) for item in value) + "]"
    return repr(value)


def _constant_names(recording: Recording, values: Optional[dict] = None) -> dict:
    """One module-level constant per distinct object definition.

    `values`, if given, is filled with what each constant should hold: the
    ordered list of definitions that all identified the object when it was
    recorded, so a step has more than one way to find it.
    """
    names: dict = {}
    used: set = set()
    if values is None:
        values = {}
    for action in recording.actions:
        if action.target is None:
            continue
        definition = action.target.definition
        label = action.target.label
        if is_item(definition):
            # The constant is the view; the row is chosen at run time, by text.
            # One constant per view rather than one per row keeps a script that
            # touches twenty rows readable.
            definition = definition["container"]
            label = (definition.get("objectName") or definition.get("type")
                     or "view")
        key = _render(definition)
        if key in names:
            continue
        values[key] = (definition if is_item(action.target.definition)
                       else action.target.candidates)
        base = _identifier(label, "object").upper()
        candidate = base
        suffix = 2
        while candidate in used:
            candidate = f"{base}_{suffix}"
            suffix += 1
        used.add(candidate)
        names[key] = candidate
    return names


def _target_expression(action, constants: dict) -> str:
    if is_item(action.target.definition):
        return _item_expression(action, constants)
    definition = _render(action.target.definition)
    name = constants[definition]
    if action.target.index is None:
        # `find` chooses among the candidates and waits for one to be usable.
        return f"find({name})"
    # Qat definitions have no index selector, so a positional target has to be
    # expressed as a lookup. It is fragile by construction and says so above.
    return f"qat.find_all_objects(find({name}))[{action.target.index}]"


def _item_expression(action, constants: dict) -> str:
    """A row, looked up by the text it showed when it was recorded."""
    definition = action.target.definition
    view = constants[_render(definition["container"])]
    parts = [view, repr(action.target.item_text)]
    column = definition.get("column", 0)
    if column:
        parts.append(f"column={column}")
    parts.append(f"recorded={definition.get('row', 0)}")
    # The property this view uses to say what is selected, if it has one. The
    # second way to do the step, for views that will not let an item be clicked.
    select = action.args.get("select")
    if select:
        parts.append(f"select={select!r}")
    return f"row({', '.join(parts)})"



#: The panel reads these back out of the generated script to show a gap where it
#: happened and offer to fill it. One line, and a comment, so a script with an
#: open gap is still valid Python and still runs -- it simply does not do the
#: thing nobody could name.
DROP_MARKER = "# QAT_DROPPED_EVENT: "


def _drop_marker(index: int, drop) -> str:
    """One line describing a gap, machine-readable, at four-space indent.

    `index` is the drop's position in `recording.drops`, and it is what the
    panel sends back to say which gap it is filling.
    """
    return "    " + DROP_MARKER + json.dumps({
        "index": index,
        "kind": drop.kind,
        "reason": drop.reason,
        "label": drop.label,
        "seen": drop.seen,
        # Whether a fix can be offered at all, and if not, the count that says
        # why. A definition matching fourteen check boxes is not a locator.
        "checked": bool(drop.suggestion),
        "matched": drop.matched,
        # What the offered fix is worth. "the third check box in this group" is
        # a real answer and a fragile one, and the operator decides knowing that
        # rather than after a rerun.
        # A window that was closed cannot be looked for, so this is the one
        # repair offered without a check. The panel says so before it is taken.
        "closed_as": (drop.evidence or {}).get("closed_proposal") or None,
        # What the filter reported, scoped by whatever contained it. Offered
        # when the application can no longer be asked -- a dialog that has
        # closed takes its buttons with it, and every honest answer about them
        # is "I cannot see it", which is not a repair.
        "reported_as": (drop.evidence or {}).get("reported_proposal") or None,
        # How many of the objects the recorder found can actually become a step.
        # Nought means there is nothing for anybody to choose between, and
        # asking a model produces a considered refusal every time.
        "usable": len([one for one in (drop.evidence or {}).get("candidates", ())
                       if one.get("target")]),
        "grade": drop.suggestion.get("robustness", ""),
        "fix_label": drop.suggestion.get("label", ""),
    }, ensure_ascii=False)


def _call_for(action, constants: dict) -> list:
    """Return the source lines for one action."""
    lines = []

    if action.target is not None:
        robustness = action.target.robustness
        if robustness in (Robustness.WEAK, Robustness.FRAGILE):
            for warning in action.target.warnings:
                lines.append(f"    # {robustness.value}: {warning}")

    if action.kind is ActionKind.LAUNCH:
        return lines

    if action.kind is ActionKind.CLOSE:
        lines.append("    qat.close_application()")
        return lines

    if action.kind is ActionKind.SCREENSHOT:
        path = action.args.get("path", "screenshot.png")
        lines.append(f"    qat.take_screenshot({path!r})")
        return lines

    if action.kind is ActionKind.CUSTOM_CODE:
        code = action.args.get("code", "")
        for line in code.splitlines():
            lines.append(f"    {line}")
        return lines

    target = _target_expression(action, constants)
    extra = ""
    if action.args.get("modifiers"):
        extra += f"  # with {action.args['modifiers']}"

    if action.kind is ActionKind.CLICK:
        button = action.args.get("button")
        if is_item(action.target.definition):
            # Through the retrying helper: a row can be findable and not yet
            # drawable, which Qat reports as a failure rather than waiting.
            call = target.replace("row(", "click_row(", 1)
            if button == "right":
                call = call[:-1] + ", button=qat.Button.RIGHT)"
            lines.append(f"    {call}{extra}")
        elif button == "right":
            lines.append(
                f"    qat.mouse_click({target}, button=qat.Button.RIGHT){extra}")
        elif is_menu_item(action.target.definition):
            lines.append(f"    menu_item({target}){extra}")
        else:
            lines.append(f"    qat.mouse_click({target}){extra}")
    elif action.kind is ActionKind.CONTEXT_CLICK:
        lines.append(
            f"    qat.mouse_click({target}, button=qat.Button.RIGHT){extra}")
    elif action.kind is ActionKind.DOUBLE_CLICK:
        lines.append(f"    qat.double_click({target}){extra}")
    elif action.kind is ActionKind.TYPE:
        lines.append(f"    qat.type_in({target}, {_render(action.args.get('text', ''))})")
    elif action.kind is ActionKind.KEY:
        lines.append(f"    qat.press_key({target}, {action.args.get('key', '')!r})")
    elif action.kind is ActionKind.SHORTCUT:
        lines.append(f"    qat.shortcut({target}, {action.args.get('keys', '')!r})")
    elif action.kind is ActionKind.SET_CHECKED:
        lines.append(f"    qat.mouse_click({target})")
    elif action.kind is ActionKind.SELECT:
        # A value, not the gesture that produced it. `wait_for_object` first
        # because the constant is a definition -- assigning to the dict itself
        # would set an attribute on a dictionary and change nothing in the
        # application.
        prop = action.args.get("property", "currentText")
        value = action.args.get("value")
        lines.append(f"    qat.wait_for_object({target}).{prop} = {_render(value)}")
    elif action.kind is ActionKind.VERIFY_PROPERTY:
        prop = action.args.get("property", "text")
        expected = action.args.get("expected")
        lines.append(f"    assert qat.wait_for_object({target}).{prop} == "
                     f"{_render(expected)}")
    elif action.kind is ActionKind.WHEEL:
        # Not produced by the recorder any more -- a scroll of so many degrees
        # depends on how much content happens to be there. Kept so recordings
        # made before that decision still generate.
        lines.append(f"    qat.mouse_wheel({target}, "
                     f"x_degrees={action.args.get('dx', 0)}, "
                     f"y_degrees={action.args.get('dy', 0)})")
    elif action.kind is ActionKind.DRAG:
        lines.append(f"    qat.mouse_drag({target}, dx={action.args.get('dx', 0)},"
                     f" dy={action.args.get('dy', 0)})")
    elif action.kind is ActionKind.CLOSE_WINDOW:
        # `close()` is a slot on every QWidget, and it is what the window
        # manager's X asks the application to do.
        lines.append(f"    qat.wait_for_object({target}).close()")
    elif action.kind is ActionKind.WAIT_MISSING:
        lines.append(f"    qat.wait_for_object_missing({target})")
    else:
        lines.append(f"    # unsupported action: {action.kind.value}")

    if action.note:
        lines[-1] += f"  # {action.note}"
    return lines


#: Qat waits three seconds for an object. That is fine for a button and not for
#: a dialog that has to read a file, so the wait is derived from the recording
#: instead: the pauses a person left between actions are evidence of how long
#: this application makes them wait. Doubled, floored, and capped so a
#: recording where somebody went for coffee does not produce a test that hangs
#: for an hour.
MIN_TIMEOUT_MS = 10_000
MAX_TIMEOUT_MS = 120_000

#: A ceiling on how long to hunt for an object. Separate from the step timeout,
#: which answers "how slow is this application"; this one answers "how long
#: before we accept it is not there", and the answers are different.
FIND_TIMEOUT_MS = 20_000


def derived_timeout(recording: Recording) -> int:
    times = [action.t for action in recording.actions]
    gaps = [later - earlier for earlier, later in zip(times, times[1:])]
    longest = max(gaps) if gaps else 0.0
    return int(min(MAX_TIMEOUT_MS, max(MIN_TIMEOUT_MS, longest * 2000)))


def _timeout_block(recording: Recording) -> list:
    timeout = derived_timeout(recording)
    return [
        "",
        "# How long to wait for an object. Qat's own default is 3s; this is",
        "# taken from the longest pause in the recorded session, because that is",
        "# how long this application actually kept someone waiting.",
        f"TIMEOUT_MS = int(os.environ.get('QATREC_TIMEOUT_MS') or {timeout})",
        "",
        "# How long to keep looking for an object before admitting it is not",
        "# coming. Shorter than the step timeout on purpose: waiting two",
        "# minutes says nothing that fifteen seconds did not.",
        f"FIND_TIMEOUT_MS = int(os.environ.get('QATREC_FIND_TIMEOUT_MS') "
        f"or {FIND_TIMEOUT_MS})",
    ]


def _preconditions(items: list, constants: dict) -> list:
    """A check, before anything is touched, of what the recording assumed.

    A test recorded against a torrent called ubuntu.iso needs that row to exist.
    Without this it half-runs and fails somewhere in the middle, leaving dialogs
    open and the application in a state nobody chose. Failing first, naming
    everything that is missing at once, is worth more than failing early on the
    first of them.
    """
    wanted = []
    seen = set()
    for action in items:
        text = action.target.item_text
        if not text:
            continue
        view = constants[_render(action.target.definition["container"])]
        key = (view, text)
        if key in seen:
            continue
        seen.add(key)
        wanted.append((view, text, action.target.definition.get("row", 0)))

    if not wanted:
        return []

    lines = ["", "def preconditions():",
             '    """What this recording assumes was already on screen."""',
             "    missing = []"]
    for view, text, recorded in wanted:
        lines.append(f"    try:")
        lines.append(f"        row({view}, {text!r}, recorded={recorded})")
        lines.append(f"    except (AssertionError, LookupError):")
        lines.append(f"        missing.append({text!r} + ' in ' + str({view}))")
    lines.extend([
        "    if missing:",
        "        raise AssertionError(",
        "            'this test was recorded against data that is not here: '",
        "            + ', '.join(missing) +",
        "            '. Put the application into that state, or re-record.')",
        "",
    ])
    return lines


def emit_object_map(recording: Recording) -> str:
    """The object map that ships beside a generated test.

    Empty of overrides on purpose: nothing should change behind the operator's
    back. What it does carry is the list of controls the application gave no
    durable identity, with the definition the recorder settled for, so fixing
    one is copying a line up and editing it rather than working out what to
    write from nothing.
    """
    constants = _constant_names(recording)
    weak = {}
    for action in recording.actions:
        target = action.target
        if target is None or target.robustness not in (
                Robustness.WEAK, Robustness.FRAGILE):
            continue
        definition = target.definition
        if is_item(definition):
            definition = definition["container"]
        name = constants.get(_render(definition))
        if name and name not in weak:
            weak[name] = dict(definition)

    document = {
        "_help": [
            "Definitions supplied by hand. Anything at the top level of this "
            "file replaces what the recorder worked out, for every test in "
            "this folder.",
            "Copy an entry out of _weak, put it at the top level, and edit it "
            "-- an objectName someone added to the application, an "
            "accessibleName, any property that does not change when the "
            "product is translated.",
            "Nothing is overridden while this file has no top-level entries.",
        ],
        "_weak": weak,
    }
    return json.dumps(document, indent=2, sort_keys=False) + "\n"


def emit_python(recording: Recording, test_name: str = "test_recorded_session",
                source: str = "recording.json") -> str:
    problems = recording.validate()
    if problems:
        raise ValueError("cannot emit an invalid recording: " + "; ".join(problems))

    values: dict = {}
    constants = _constant_names(recording, values)

    out = [HEADER.format(source=source), ""]
    definitions = [action.target.definition for action in recording.actions
                   if action.target is not None]
    out.append(OVERRIDE_HELPER)
    if recording.meta.get("app_path"):
        out.append(LAUNCH_HELPER)
    if any(is_menu_item(definition) for definition in definitions):
        out.append(MENU_HELPER)
    items = [action for action in recording.actions
             if action.target is not None and is_item(action.target.definition)]
    if items:
        out.append(ITEM_HELPER)

    for definition, name in constants.items():
        # Every way this object was findable when it was recorded, best first.
        out.append(f"{name} = override({name!r}, "
                   f"{_render(values.get(definition))})")
    if constants:
        out.append("")

    out.append("")
    out.append(f"APP_NAME = {recording.app!r}")
    app_path = recording.meta.get("app_path", "")
    if app_path:
        out.append(f"APP_PATH = {app_path!r}")
    out.extend(_timeout_block(recording))
    out.append("")
    out.append("")
    out.append("@pytest.fixture()")
    out.append("def application():")
    # Registering is done by launch_application() rather than here, because a
    # launch script and a binary do not need the same registration -- and
    # because `start_application` takes a registered NAME, so a test that only
    # knows the name fails with "Application '...' is not defined in
    # configuration file 'applications.json'" on every machine except the one it
    # was recorded on.
    out.append("    qat.Settings.wait_for_object_timeout = TIMEOUT_MS")
    out.append("    # The same condition the session was recorded under: Qt's")
    out.append("    # own file dialogs rather than the desktop's. A native")
    out.append("    # dialog is not a Qt widget -- Qat cannot see it, and while")
    out.append("    # one is open the application stops answering Qat at all.")
    out.append("    if os.environ.get('QATREC_NATIVE_DIALOGS') != '1':")
    out.append("        os.environ['QT_QPA_PLATFORMTHEME'] = ''")
    # Launch from the application's own directory, as the recording did.
    # Only around the launch: Qat writes applications.json into the working
    # directory, and that belongs beside the test rather than in somebody's
    # application folder.
    out.append("    _was = os.getcwd()")
    out.append("    if APP_PATH:")
    out.append("        os.chdir(os.path.dirname(os.path.abspath(APP_PATH)))")
    out.append("    try:")
    if app_path:
        out.append("        context = launch_application(APP_NAME, APP_PATH)")
    else:
        out.append("        context = qat.start_application(APP_NAME)")
    out.append("    finally:")
    out.append("        os.chdir(_was)")
    out.append("    yield context")
    if app_path:
        out.append("    close_application(context)")
    else:
        out.append("    qat.close_application(context)")
    out.append("")
    checks = _preconditions(items, constants)
    out.extend(checks)
    out.append("")
    out.append(f"def {_identifier(test_name, 'test_recorded')}(application):")

    body = []
    # Only when the function was actually emitted. It is not, when no row has
    # any text to check -- and calling a function that was never written is a
    # NameError before a single step runs, which is exactly what shipped.
    if checks:
        body.append("    preconditions()")
    # Gaps are placed among the steps rather than listed at the end. A drop
    # after three actions belongs between the third and the fourth, which is the
    # only place it means anything to the person who has to fill it.
    open_gaps = {}
    for position, drop in enumerate(recording.drops):
        if not drop.repaired:
            open_gaps.setdefault(drop.after, []).append((position, drop))

    def _gaps_at(index: int) -> list:
        return [_drop_marker(position, drop)
                for position, drop in open_gaps.get(index, ())]

    for index, action in enumerate(recording.actions):
        body.extend(_gaps_at(index))
        body.extend(_call_for(action, constants))
    body.extend(_gaps_at(len(recording.actions)))
    if not body:
        body.append("    pass")
    out.extend(body)
    out.append("")

    gaps = recording.open_drops()
    if gaps:
        out.append("")
        out.append(f"# {len(gaps)} event(s) could not be recorded, and this "
                   "script does not do them.")
        out.append("# It will pass without them. Each is marked above, at the "
                   "point it happened.")
        for drop in gaps:
            out.append(f"#   {drop.kind} on {drop.label}: {drop.reason}")
        out.append("")

    weakest = recording.weakest_targets()
    if weakest:
        out.append("")
        out.append("# Review before relying on this script:")
        for action in weakest:
            out.append(f"#   {action.target.robustness.value:<10} "
                       f"{action.target.label} -> {action.target.definition}")
        out.append("")

    return "\n".join(out)
