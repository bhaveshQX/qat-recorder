# -*- coding: utf-8 -*-
"""
Token and TLS for the agent.

The agent launches processes on request, so an unauthenticated one is a remote
execution service. Both legs are therefore mandatory rather than optional:
the agent refuses to start without a token, and refuses to serve plaintext
unless explicitly forced for a local test.

Certificates are generated by shelling out to `openssl`, which is present on
every target distribution, rather than adding a dependency on `cryptography` to
a package that otherwise needs nothing.
"""

from __future__ import annotations

import hmac
import os
import secrets
import shutil
import ssl
import subprocess
from pathlib import Path
from typing import Optional

TOKEN_ENV = "QATREC_AGENT_TOKEN"
TOKEN_BYTES = 32


def generate_token() -> str:
    return secrets.token_urlsafe(TOKEN_BYTES)


def load_token(explicit: Optional[str] = None,
               token_file: Optional[str] = None) -> str:
    """Resolve the shared token, preferring the least leaky source.

    A token on the command line ends up in `ps` output and shell history, so a
    file or the environment is preferred; passing one directly is still allowed
    because it is convenient in a container.
    """
    if token_file:
        text = Path(token_file).read_text(encoding="utf-8").strip()
        if not text:
            raise ValueError(f"token file {token_file} is empty")
        return text
    if explicit:
        return explicit
    from_env = os.environ.get(TOKEN_ENV, "").strip()
    if from_env:
        return from_env
    raise ValueError(
        "no token: set QATREC_AGENT_TOKEN, pass --token-file, or run "
        "`qat-recorder-agent --generate-token`")


def token_matches(expected: str, presented: Optional[str]) -> bool:
    """Constant-time comparison, so a wrong token cannot be found byte by byte."""
    if not presented:
        return False
    return hmac.compare_digest(expected, presented)


def parse_bearer(header: Optional[str]) -> Optional[str]:
    if not header:
        return None
    parts = header.split(None, 1)
    if len(parts) != 2 or parts[0].lower() != "bearer":
        return None
    return parts[1].strip()


